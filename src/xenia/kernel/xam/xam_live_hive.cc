std::optional<std::string_view> GetLiveHiveValue(std::string_view name) {
  static const auto hive = []() {
    std::unordered_map<std::string, std::string_view> entries;

    for (const auto& [key, value] : kLiveHive) {
      entries.emplace(xe::utf8::lower_ascii(key), value);
    }

    return entries;
  }();

  const auto entry = hive.find(xe::utf8::lower_ascii(name));

  if (entry == hive.end()) {
    return std::nullopt;
  }

  return entry->second;
}

